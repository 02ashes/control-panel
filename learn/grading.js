const GATE = {
  molchun_open: 'не давит', sales_no_money: 'не клянчит', sexting_bundle: 'описание',
  custom_pitch: 'под него', videocall_upsell: 'допка', chipcustom_open: 'секрет/доверие',
  tg_move: 'предлог', threesome_open: 'двое', fetish_open: 'под фетиш'
};
function clampVerdict(result, task) {
  const crit = (result && result.criteria) || {};
  const vals = Object.values(crit).map(v => Number(v) || 0);
  const sum = vals.reduce((a, b) => a + b, 0);
  const score = Math.max(0, Math.min(100, vals.length ? sum * 10 : (Number(result.score) || 0)));
  const gate = GATE[task];
  const gateOk = gate ? (Number(crit[gate]) || 0) >= 1 : true;
  const pass = score >= 60 && gateOk;
  return { score, pass, criteria: crit, feedback: String((result && result.feedback) || '') };
}

