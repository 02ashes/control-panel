function callGrok(paste, task, apiKey) {
  const system = PREAMBLE + (RUBRICS[task] || RUBRICS[DEFAULT_TASK]) + (EXAMPLES[task] || '');
  return new Promise((resolve, reject) => {
    const payload = JSON.stringify({
      model: MODEL,
      messages: [
        { role: 'system', content: system },
        { role: 'user', content: 'Сообщение новичка:\n"""' + paste + '"""' }
      ],
      response_format: { type: 'json_object' }, temperature: 0
    });
    const req = https.request({
      hostname: 'api.x.ai', path: '/v1/chat/completions', method: 'POST',
      headers: { 'Authorization': 'Bearer ' + apiKey, 'Content-Type': 'application/json', 'Content-Length': Buffer.byteLength(payload) }
    }, res => {
      let body = ''; let size = 0;
      res.on('data', d => { size += d.length; if (size > 1e6) { req.destroy(new Error('ответ Grok слишком большой')); return; } body += d; });
      res.on('end', () => {
        try {
          const j = JSON.parse(body);
          const c = j.choices && j.choices[0] && j.choices[0].message && j.choices[0].message.content;
          if (!c) return reject(new Error(j.error ? (j.error.message || JSON.stringify(j.error)) : 'пустой ответ'));
          resolve(JSON.parse(c));
        } catch (e) { reject(new Error('не распарсил ответ Grok')); }
      });
    });
    req.on('error', reject);
    req.setTimeout(30000, () => req.destroy(new Error('таймаут Grok')));
    req.write(payload); req.end();
  });
}

